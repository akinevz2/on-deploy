// src/commands/detect-server.ts — probe a REACHABLE X server and expose
// the result.
//
//	on-deploy detect-server
//	on-deploy detect-server <address>
//	on-deploy detect-server --persist-to-systemd
//	on-deploy detect-server --persist-to-env=<file>
//	on-deploy detect-server <address> --persist-to-env=/etc/rc.d/x11-display
//	... --dry-run: print what would be persisted, change nothing
//
// Success prints the display string ("localhost:0.0" notation) on stdout;
// exit 0 = reachable, exit 1 = probe failed, exit 2 = usage. Stdout carries
// ONLY the display string; all diagnostics go to stderr.
//
// Optional final positional <address>: an explicit display address to CHECK
// and persist instead of autodetecting (servers running elsewhere). It is
// wrapped in quotes in every generated line so the persisted env is safe.
//
// Persistence:
//	--persist-to-systemd	if systemd is present, ALSO set the variable in
//                         the user manager's environment (systemctl --user
//	set-environment DISPLAY=<d>) so all user units
//	inherit it. No-op + exit 1 when systemd is absent
//	(SysV targets must not turn this into a fatal).
//	--persist-to-env=<f>	ALSO write an executable sh snippet
//                         (chmod 755) with `export DISPLAY="<d>"` so SysV
//	rc.d scripts can include it from anywhere:
//	. /etc/rc.d/x11-display
//	(it is sourced; it may also be executed directly.)
//
// Probe order without <address>: inherited $DISPLAY, localhost:0.0,
// localhost:1.0, :0, :1 — the shared detectDisplay (also rewrites the
// child-spawn env for the rest of this process when it succeeds).

import { defineCommand, option } from "@bunli/core";
import { say } from "../lib/lines";
import { bind, flush, pure, type Out } from "../lib/out";
import { z } from "zod";
import { existsSync, writeFileSync, chmodSync } from "node:fs";
import { detectDisplay, sh } from "../lib/provisioners";

/** probeAddress — true when `xset q -display <d>` answers within 2s
 * (timeout guards the half-open VcXsrv-connection hang). */
function probeAddress(d: string): boolean {
    const xset = sh("sh", ["-c", "command -v xset"]).out;
    if (!xset) return false;
    return sh("timeout", ["2", xset, "q", "-display", d]).code === 0;
}

/** persistSystemd — set DISPLAY in the systemd user manager environment.
 *  Detects systemd by binary presence + an answering `systemctl --user`;
 *  returns an Out<boolean> (diagnostics ride the lines) rather than
 *  printing: [FLUSH-CLASS: buffered] — the sh() probes are piped. */
function persistSystemd(display: string): Out<boolean> {
    if (!sh("sh", ["-c", "command -v systemctl"]).out) {
        return pure(false, "detect-server: systemd not present — skipping --persist-to-systemd");
    }
    const up = sh("sh", ["-c", "systemctl --user >/dev/null 2>&1"]);
    if (up.code !== 0) {
        return pure(false, "detect-server: systemd user session not reachable — skipping --persist-to-systemd");
    }
    const r = sh("systemctl", ["--user", "set-environment", `DISPLAY=${display}`]);
    if (r.code === 0) {
        return pure(true, `detect-server: systemd user environment DISPLAY=${display} set`);
    }
    return pure(false, "detect-server: systemctl --user set-environment failed — skipping");
}

/** persistEnvFile — executable sh snippet with the exported variable.
 *  Sourced (`. <file>`) by rc.d scripts anywhere, or run directly.
 *  [FLUSH-CLASS: buffered] — filesystem work only, lines ride upward. */
function persistEnvFile(path: string, display: string): Out<boolean> {
    const overwrote = existsSync(path);
    const body =
        "#!/bin/sh\n" +
        "# x11 display address — generated by `on-deploy detect-server --persist-to-env`\n" +
        `# ${new Date().toISOString()} — include it from rc.d scripts: . ${path}\n` +
        `export DISPLAY="${display}"\n`;
    try {
        writeFileSync(path, body);
        chmodSync(path, 0o755);
        return pure(true,
            `detect-server: ${overwrote ? "rewrote" : "wrote"} ${path}` +
            " (sourced or executable: export DISPLAY set)",
        );
    } catch (e) {
        return pure(false, `detect-server: cannot write ${path}: ${e}`);
    }
}

export default defineCommand({
    name: "detect-server",
    description: "Print reachable X display",
    options: {
        "persist-to-systemd": option(z.boolean().optional(), {
            description: "set DISPLAY in the systemd --user manager environment (no-op on SysV)",
            // bunli 0.9 does NOT infer flag-ness from z.boolean(): without
            // this, the bare `--persist-to-systemd` parses to undefined
            // and the flag is silently dropped (validated as optional)
            argumentKind: "flag",
        }),
        "dry-run": option(z.boolean().optional(), {
            description: "print what would be persisted, change nothing",
            argumentKind: "flag",
        }),
        "persist-to-env": option(z.string().optional(), {
            description: "write `export DISPLAY=...` to this executable sh file (rc.d-includable)",
        }),
    },
    handler: async ({ flags, positional }) => {
        if (positional.length > 1) {
            // [FLUSH-CLASS: exit] usage report — exit code carries severity
            say("detect-server: usage: on-deploy detect-server [ADDRESS] [--persist-to-systemd] [--persist-to-env=<file>] [--dry-run]");
            process.exit(2);
        }
        const addr = positional[0];
        const dry = !!flags["dry-run"];

        let display: string;
        if (addr) {
            // explicit address: checked, never silently replaced — an
            // unreachable user-specified server is an error, not a probe miss
            if (!probeAddress(addr)) {
                // [FLUSH-CLASS: exit] failure report — exit code carries severity
                say(`detect-server: ${addr} does not answer xset q — not persisting it`);
                process.exit(1);
            }
            display = addr;
        } else {
            const r = detectDisplay();
            if (!r.ok) {
                // [FLUSH-CLASS: exit] failure report — exit code carries severity
                say(`detect-server: no reachable X display — probed:${r.probed.join(" ") || " (none)"}`);
                process.exit(1);
            }
            display = r.display;
        }

        // persist AFTER the display is known; both are best-effort but the
        // SD one failing (its stderr explains why) doesn't block the file.
        // [FLUSH-CLASS: buffered] the persist diagnostics ride Out values;
        // the same && combination shape as before, composed via bind/map
        let out: Out<boolean> = pure(true);
        if (flags["persist-to-systemd"] || flags["persist-to-env"]) {
            if (dry) {
                out = bind(out, () => pure(true,
                    `    [dry-run] ${
                        [
                            flags["persist-to-systemd"] ? `systemctl --user set-environment DISPLAY=${display}` : "",
                            flags["persist-to-env"] ? `sh -c 'export DISPLAY="${display}"' > ${flags["persist-to-env"]}` : "",
                        ].filter(Boolean).join(" && ")
                    }`,
                    display,
                ));
            } else {
                const sd = flags["persist-to-systemd"]
                    ? persistSystemd(display)
                    : pure(true);
                const env = flags["persist-to-env"]
                    ? persistEnvFile(flags["persist-to-env"] as string, display)
                    : pure(true);
                out = bind(sd, (a) => bind(env, (b) => pure(a && b, display)));
            }
        } else {
            out = bind(out, () => pure(true, display));
        }
        // [FLUSH-CLASS: exit] the buffered diagnostics + the display
        // string flush here — stdout carries ONLY the display line last,
        // then the exit code speaks
        const ok = flush(out);
        process.exit(ok ? 0 : 1);
    },
});
